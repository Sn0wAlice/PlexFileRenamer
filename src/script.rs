//! Shell scripts equivalent to `apply --mode move`, for people who'd rather read before running.

use crate::plan::{Plan, Status};
use std::collections::BTreeSet;

#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum Shell {
    Bash,
    Pwsh,
    Cmd,
}

fn parent(p: &str) -> &str {
    p.rfind('/').map(|i| &p[..i]).unwrap_or("")
}

/// POSIX single quotes: everything literal, `'` becomes `'\''`.
pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', r"'\''"))
}

/// PowerShell single quotes: literal, `'` (and its Unicode lookalikes, which pwsh also treats as quotes) doubled.
pub fn ps_quote(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        if matches!(c, '\'' | '‘' | '’' | '‚' | '‛') {
            out.push(c);
        }
        out.push(c);
    }
    out.push('\'');
    out
}

/// cmd.exe: `"` can't appear in Windows names; `%` must be doubled in a .cmd file.
pub fn cmd_quote(s: &str) -> String {
    format!("\"{}\"", s.replace('/', "\\").replace('%', "%%"))
}

fn cmd_echo(s: &str) -> String {
    let mut out = String::new();
    for c in s.chars() {
        match c {
            '%' => out.push_str("%%"),
            '^' | '&' | '|' | '<' | '>' | '(' | ')' => {
                out.push('^');
                out.push(c);
            }
            c => out.push(c),
        }
    }
    out
}

pub fn generate(plan: &Plan, shell: Shell) -> String {
    let ops: Vec<_> = plan
        .ops
        .iter()
        .filter(|o| o.status == Status::Rename)
        .collect();
    let mut dirs = BTreeSet::new();
    for o in &ops {
        dirs.insert(parent(&o.dst).to_string());
    }
    let mut s = String::new();
    match shell {
        Shell::Bash => {
            s += "#!/usr/bin/env bash\n# Generated by plexfilerenamer. mv -n never overwrites.\nset -euo pipefail\n\n";
            for d in &dirs {
                s += &format!("mkdir -p -- {}\n", sh_quote(d));
            }
            s += "\n";
            for o in &ops {
                match &o.src {
                    Some(src) => s += &format!("mv -n -- {} {}\n", sh_quote(src), sh_quote(&o.dst)),
                    None => {
                        let q = sh_quote(&o.dst);
                        s += &format!(
                            "[ -e {q} ] || printf '%s' {} > {q}\n",
                            sh_quote(o.content.as_deref().unwrap_or(""))
                        );
                    }
                }
            }
        }
        Shell::Pwsh => {
            s += "\u{feff}# Generated by plexfilerenamer. Never overwrites: File.Move fails if the target exists.\n";
            s += "$ErrorActionPreference = 'Stop'\n\n";
            for d in &dirs {
                s += &format!(
                    "[void][System.IO.Directory]::CreateDirectory({})\n",
                    ps_quote(d)
                );
            }
            s += "\n";
            for o in &ops {
                let dst = ps_quote(&o.dst);
                match &o.src {
                    Some(src) => {
                        s += &format!(
                            "if (-not (Test-Path -LiteralPath {dst})) {{ [System.IO.File]::Move({}, {dst}) }}\n",
                            ps_quote(src)
                        )
                    }
                    None => {
                        s += &format!(
                            "if (-not (Test-Path -LiteralPath {dst})) {{ [System.IO.File]::WriteAllText({dst}, {}) }}\n",
                            ps_quote(o.content.as_deref().unwrap_or(""))
                        )
                    }
                }
            }
        }
        Shell::Cmd => {
            s += "@echo off\r\nrem Generated by plexfilerenamer. Each move is guarded by \"if not exist\".\r\n";
            s += "chcp 65001 >nul\r\nsetlocal DisableDelayedExpansion\r\n\r\n";
            for d in &dirs {
                let q = cmd_quote(d);
                s += &format!("if not exist {q} mkdir {q}\r\n");
            }
            s += "\r\n";
            for o in &ops {
                let dst = cmd_quote(&o.dst);
                match &o.src {
                    Some(src) => {
                        s += &format!("if not exist {dst} move {} {dst} >nul\r\n", cmd_quote(src))
                    }
                    None => {
                        s += &format!("if not exist {dst} (\r\n");
                        for (i, line) in o.content.as_deref().unwrap_or("").lines().enumerate() {
                            let redir = if i == 0 { ">" } else { ">>" };
                            s += &format!("  {redir}{dst} echo {}\r\n", cmd_echo(line));
                        }
                        s += ")\r\n";
                    }
                }
            }
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(sh_quote("Ocean's $HOME `x` é"), r"'Ocean'\''s $HOME `x` é'");
        assert_eq!(ps_quote("It's ’ok’"), "'It''s ’’ok’’'");
        assert_eq!(cmd_quote("/a/100% b"), "\"\\a\\100%% b\"");
    }

    /// The bash quoting must survive a real shell round-trip.
    #[cfg(unix)]
    #[test]
    fn bash_roundtrip() {
        let nasty = "Ocean's $HOME \"q\" `id` \\ é 日本 !x * ?";
        let out = std::process::Command::new("bash")
            .arg("-c")
            .arg(format!("printf '%s' {}", sh_quote(nasty)))
            .output()
            .unwrap();
        assert_eq!(String::from_utf8(out.stdout).unwrap(), nasty);
    }
}
